items = []
seen_answers = set()

def make_question(ans):
    # Reverse character-by-character and join with spaces
    rev = ans[::-1]
    return " ".join(list(rev))

all_raw = []
for ans, hint in easy_data:
    all_raw.append(("easy", ans, hint))
for ans, hint in medium_data:
    all_raw.append(("medium", ans, hint))
for ans, hint in hard_data:
    all_raw.append(("hard", ans, hint))

assert len(all_raw) == 200, f"Expected 200, got {len(all_raw)}"

for idx, (diff, ans, hint) in enumerate(all_raw, start=1):
    assert ans not in seen_answers, f"Duplicate: {ans}"
    seen_answers.add(ans)
    q = make_question(ans)
    items.append({
        "id": idx,
        "difficulty": diff,
        "question": q,
        "answer": ans,
        "hint": hint
    })

output = {
    "category": "الكلمات المعكوسة",
    "items": items
}

json_str = json.dumps(output, ensure_ascii=False, indent=2)
print(json_str[:1000])
print("TOTAL ITEMS:", len(items))
with open("reversed_words.json", "w", encoding="utf-8") as f:
    f.write(json_str)

